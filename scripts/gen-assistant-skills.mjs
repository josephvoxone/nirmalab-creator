#!/usr/bin/env node
// Builds server/src/assistant/skills-text.ts from server/src/assistant/skills/*.md.
// tsc does not copy .md files into server/dist, so the assistant's skills pack ships as string
// constants. Run after editing a skill file: `pnpm gen:skills` (a test fails when they drift).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'server/src/assistant/skills');
const names = readdirSync(dir).filter(f => f.endsWith('.md')).sort().map(f => f.slice(0, -3));
const body = names.map(name => `  ${name}: ${JSON.stringify(readFileSync(join(dir, `${name}.md`), 'utf8'))}`).join(',\n');
const out = `// Generated by scripts/gen-assistant-skills.mjs from server/src/assistant/skills/*.md — do not edit.
// Edit the .md file, then run \`pnpm gen:skills\`.
export const SKILL_FILES = {
${body}
} as const;
`;
writeFileSync(join(root, 'server/src/assistant/skills-text.ts'), out);
console.log(`skills-text.ts: ${names.join(', ')}`);
